import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const receiver = path.dirname(fileURLToPath(import.meta.url));
const defaultOutput = path.resolve(receiver, '.work', 'pwa');
const MAX_BROWSER_CACHE_BYTES = 8 * 1024 * 1024;

function buildArguments(argv) {
  const options = { output: defaultOutput, embedModule: undefined };
  for (let index = 0; index < argv.length; index += 2) {
    const name = argv[index];
    const value = argv[index + 1];
    if (!value) {
      throw new Error(
        'usage: build.mjs [--output DIRECTORY] [--embed-module FILE]',
      );
    }
    if (name === '--output') {
      options.output = path.resolve(value);
    } else if (name === '--embed-module') {
      options.embedModule = path.resolve(value);
    } else {
      throw new Error(`unknown receiver build option: ${name}`);
    }
  }
  return options;
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function replaceRequired(template, replacements, name) {
  let output = template;
  for (const [placeholder, value] of Object.entries(replacements)) {
    if (!output.includes(placeholder)) {
      throw new Error(`${name} has no ${placeholder} placeholder`);
    }
    output = output.replaceAll(placeholder, value);
  }
  if (/__DUD_OPTICAL_[A-Z_]+__/.test(output)) {
    throw new Error(`${name} retains an optical build placeholder`);
  }
  return output;
}

function fingerprint(name, bytes) {
  const extension = path.extname(name);
  const stem = name.slice(0, -extension.length);
  return `${stem}.${sha256(bytes)}${extension}`;
}

function writeAsset(output, name, bytes) {
  writeFileSync(path.join(output, name), bytes);
  return {
    path: name,
    bytes: bytes.byteLength,
    sha256: sha256(bytes),
  };
}

function writeEmbeddedModule(filename, buildID, entrypoint, assets) {
  const records = Object.fromEntries(
    assets.map((asset) => [
      asset.path,
      {
        contentType: asset.contentType,
        immutable: asset.immutable,
        sha256: asset.sha256,
        bytes: asset.bytes.toString('base64'),
      },
    ]),
  );
  const source = `// SPDX-License-Identifier: MIT
// Copyright (C) 2026 Wojciech Polak
// Generated by server/optical-receiver/build.mjs. Do not edit.

export interface EmbeddedOpticalPwaAsset {
  readonly contentType: string;
  readonly immutable: boolean;
  readonly sha256: string;
  readonly bytes: string;
}

export interface EmbeddedOpticalPwaBuild {
  readonly buildId: string;
  readonly entrypoint: string;
  readonly assets: Readonly<Record<string, EmbeddedOpticalPwaAsset>>;
}

export const OPTICAL_PWA_BUILD: EmbeddedOpticalPwaBuild = ${JSON.stringify(
    { buildId: buildID, entrypoint, assets: records },
    null,
    2,
  )};
`;
  mkdirSync(path.dirname(filename), { recursive: true });
  writeFileSync(filename, source);
}

const options = buildArguments(process.argv.slice(2));
const output = options.output;
const staging = path.join(
  path.dirname(output),
  `${path.basename(output)}-staging`,
);
rmSync(staging, { recursive: true, force: true });
rmSync(output, { recursive: true, force: true });
mkdirSync(staging, { recursive: true });
mkdirSync(output, { recursive: true });

const common = {
  absWorkingDir: receiver,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  sourcemap: false,
  legalComments: 'eof',
};
for (const entry of ['app', 'decoder-worker', 'fountain-worker']) {
  const bundled = await build({
    ...common,
    metafile: true,
    entryPoints: [path.join(receiver, 'src', `${entry}.ts`)],
    outfile: path.join(staging, `${entry}.js`),
  });
  const bytes = readFileSync(path.join(staging, `${entry}.js`));
  if (
    Object.keys(bundled.metafile.inputs).some(
      (name) => name.includes('node_modules') || name.endsWith('.wasm'),
    ) ||
    /WebAssembly|zbar|ZBar/.test(bytes.toString('utf8'))
  ) {
    throw new Error(
      'optical browser bundles must contain only repository JavaScript',
    );
  }
}
const workerBytes = readFileSync(path.join(staging, 'decoder-worker.js'));
const fountainBytes = readFileSync(path.join(staging, 'fountain-worker.js'));

const publicDirectory = path.join(receiver, 'public');
const noticeBytes = readFileSync(
  path.join(publicDirectory, 'third-party-notices.txt'),
);
const inputs = new Map([
  ['app.js', readFileSync(path.join(staging, 'app.js'))],
  ['decoder-worker.js', workerBytes],
  ['fountain-worker.js', fountainBytes],
  ['index.html', readFileSync(path.join(publicDirectory, 'index.html'))],
  [
    'manifest.webmanifest',
    readFileSync(path.join(publicDirectory, 'manifest.webmanifest')),
  ],
  [
    'receiver-icon.svg',
    readFileSync(path.join(publicDirectory, 'receiver-icon.svg')),
  ],
  ['styles.css', readFileSync(path.join(publicDirectory, 'styles.css'))],
  ['sw.js', readFileSync(path.join(publicDirectory, 'sw.js'))],
  ['third-party-notices.txt', noticeBytes],
]);

const buildHash = createHash('sha256');
for (const [name, bytes] of inputs) {
  buildHash.update(name);
  buildHash.update('\0');
  buildHash.update(bytes);
  buildHash.update('\0');
}
const buildID = buildHash.digest('hex').slice(0, 12);

const workerName = fingerprint('decoder-worker.js', workerBytes);
const fountainName = fingerprint('fountain-worker.js', fountainBytes);
const appTemplate = inputs.get('app.js').toString('utf8');
const appSource = replaceRequired(
  appTemplate,
  {
    './decoder-worker.js': `./${workerName}`,
    './fountain-worker.js': `./${fountainName}`,
  },
  'app.js',
);
const appBytes = Buffer.from(appSource);
const appName = fingerprint('app.js', appBytes);
const styleBytes = inputs.get('styles.css');
const styleName = fingerprint('styles.css', styleBytes);
const iconBytes = inputs.get('receiver-icon.svg');
const iconName = fingerprint('receiver-icon.svg', iconBytes);
const noticeName = fingerprint('third-party-notices.txt', noticeBytes);
const indexName = `index.${buildID}.html`;

const manifestSource = replaceRequired(
  inputs.get('manifest.webmanifest').toString('utf8'),
  {
    __DUD_OPTICAL_ICON__: `./${iconName}`,
  },
  'manifest.webmanifest',
);
const manifestBytes = Buffer.from(manifestSource);
const manifestName = fingerprint('manifest.webmanifest', manifestBytes);

const indexSource = replaceRequired(
  inputs.get('index.html').toString('utf8'),
  {
    __DUD_OPTICAL_APP__: `./${appName}`,
    __DUD_OPTICAL_BUILD__: buildID,
    __DUD_OPTICAL_ICON__: `./${iconName}`,
    __DUD_OPTICAL_MANIFEST__: './manifest.webmanifest',
    __DUD_OPTICAL_NOTICES__: `./${noticeName}`,
    __DUD_OPTICAL_STYLE__: `./${styleName}`,
  },
  'index.html',
);
const indexBytes = Buffer.from(indexSource);

const contentTypes = {
  [indexName]: 'text/html; charset=utf-8',
  [appName]: 'text/javascript; charset=utf-8',
  [workerName]: 'text/javascript; charset=utf-8',
  [fountainName]: 'text/javascript; charset=utf-8',
  [styleName]: 'text/css; charset=utf-8',
  [manifestName]: 'application/manifest+json; charset=utf-8',
  [iconName]: 'image/svg+xml',
  [noticeName]: 'text/plain; charset=utf-8',
  'index.html': 'text/html; charset=utf-8',
  'manifest.webmanifest': 'application/manifest+json; charset=utf-8',
  'sw.js': 'text/javascript; charset=utf-8',
};
const immutableBytes = new Map([
  [indexName, indexBytes],
  [appName, appBytes],
  [workerName, workerBytes],
  [fountainName, fountainBytes],
  [styleName, styleBytes],
  [manifestName, manifestBytes],
  [iconName, iconBytes],
  [noticeName, noticeBytes],
]);
const immutablePaths = [
  indexName,
  appName,
  workerName,
  fountainName,
  styleName,
  manifestName,
  iconName,
  noticeName,
];
const browserCacheBytes = immutablePaths.reduce(
  (total, name) => total + immutableBytes.get(name).byteLength,
  0,
);
if (browserCacheBytes > MAX_BROWSER_CACHE_BYTES) {
  throw new Error(
    `receiver cache size ${browserCacheBytes} exceeds ${MAX_BROWSER_CACHE_BYTES}`,
  );
}
const serviceWorkerSource = replaceRequired(
  inputs.get('sw.js').toString('utf8'),
  {
    __DUD_OPTICAL_CACHE_ENTRIES__: JSON.stringify(
      immutablePaths.map((name) => ({
        url: `./${name}`,
        contentType: contentTypes[name],
        byteLength: immutableBytes.get(name).byteLength,
        bytes: immutableBytes.get(name).toString('base64'),
      })),
      null,
      2,
    ),
    __DUD_OPTICAL_BUILD__: buildID,
    __DUD_OPTICAL_INDEX__: `./${indexName}`,
    __DUD_OPTICAL_MANIFEST__: `./${manifestName}`,
  },
  'sw.js',
);
const serviceWorkerBytes = Buffer.from(serviceWorkerSource);

const assets = [
  writeAsset(output, indexName, indexBytes),
  writeAsset(output, appName, appBytes),
  writeAsset(output, workerName, workerBytes),
  writeAsset(output, fountainName, fountainBytes),
  writeAsset(output, styleName, styleBytes),
  writeAsset(output, manifestName, manifestBytes),
  writeAsset(output, iconName, iconBytes),
  writeAsset(output, noticeName, noticeBytes),
  writeAsset(output, 'index.html', indexBytes),
  writeAsset(output, 'manifest.webmanifest', manifestBytes),
  writeAsset(output, 'sw.js', serviceWorkerBytes),
].map((asset) => ({
  ...asset,
  contentType: contentTypes[asset.path],
  immutable: immutablePaths.includes(asset.path),
}));

const buildManifest = {
  schemaVersion: 1,
  buildId: buildID,
  basePath: '/optical/',
  entrypoint: indexName,
  browserCache: {
    bytes: browserCacheBytes,
    limitBytes: MAX_BROWSER_CACHE_BYTES,
  },
  assets,
};
const buildManifestBytes = Buffer.from(
  `${JSON.stringify(buildManifest, null, 2)}\n`,
);
writeFileSync(path.join(output, 'build-manifest.json'), buildManifestBytes);
if (options.embedModule) {
  writeEmbeddedModule(options.embedModule, buildID, indexName, [
    ...assets.map((asset) => ({
      ...asset,
      bytes: readFileSync(path.join(output, asset.path)),
    })),
    {
      path: 'build-manifest.json',
      contentType: 'application/json; charset=utf-8',
      immutable: false,
      sha256: sha256(buildManifestBytes),
      bytes: buildManifestBytes,
    },
  ]);
}
rmSync(staging, { recursive: true, force: true });
console.log(`built optical receiver PWA ${buildID} in ${output}`);
