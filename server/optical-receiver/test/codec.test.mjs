function bytes(hex) {
  return Uint8Array.from({ length: hex.length / 2 }, (_, index) =>
    Number.parseInt(hex.slice(index * 2, index * 2 + 2), 16),
  );
}

function hex(value) {
  return Array.from(value, (byte) => byte.toString(16).padStart(2, '0')).join(
    '',
  );
}

function vectorCapsule(length) {
  return Uint8Array.from(
    { length },
    (_, index) =>
      (Math.imul(index, 73) + Math.imul(index >>> 8, 19) + 41) & 0xff,
  );
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function assertCodecError(error, code) {
  assert.ok(
    error instanceof OpticalCodecError,
    `got ${error}, wanted OpticalCodecError`,
  );
  assert.equal(error.code, code);
  return true;
}

function assertSelectionVectors(sessionId) {
  for (const vector of vectors.selection) {
    assert.deepEqual(
      selectBlocks(
        sessionId,
        vector.stripe,
        vector.sequence,
        vector.sourceCount,
      ),
      vector.selected,
    );
  }
}

async function assertCaseVector(vector, sessionId) {
  assert.equal(vector.recipe, 'index-73-page-19-plus-41');
  const capsule = vectorCapsule(vector.capsuleLength);
  assert.equal(digest(capsule), vector.digest);
  const encoder = await OpticalEncoder.create(
    capsule,
    sessionId,
    vector.blockSize,
  );
  const decoder = new OpticalDecoder();
  const complete =
    vector.name === 'complete-capsule' ||
    vector.name === 'high-density-complete';
  for (const expected of vector.frames) {
    const frame = encoder.frame(expected.stripe, expected.sequence);
    assert.equal(hex(frame), expected.bytes, `${vector.name} frame bytes`);
    assert.deepEqual(
      selectBlocks(
        sessionId,
        expected.stripe,
        expected.sequence,
        encoder.getSourceCount(expected.stripe),
      ),
      expected.selected,
    );
    if (complete) {
      decoder.add(bytes(expected.bytes));
    }
  }
  if (complete) {
    assert.deepEqual(await decoder.result(), capsule);
  }
}

function assertInvalidVectors() {
  for (const vector of vectors.invalid) {
    assert.throws(
      () => parseFrame(bytes(vector.bytes)),
      (error) => assertCodecError(error, vector.code),
      vector.name,
    );
  }
}

function assertHostileVector(vector) {
  const decoder = new OpticalDecoder();
  let progress;
  let caught;
  outer: for (let repetition = 0; repetition < vector.repeat; repetition++) {
    for (const encoded of vector.frames) {
      try {
        progress = decoder.add(bytes(encoded));
      } catch (error) {
        caught = error;
        break outer;
      }
    }
  }
  const expectedCode =
    vector.name === 'endless-duplicate-stream' ? 'decoder-work' : vector.code;
  if (expectedCode) {
    assertCodecError(caught, expectedCode);
  } else {
    assert.equal(caught, undefined, vector.name);
  }
  assert.equal(progress?.independentRows, vector.independentRows, vector.name);
}

test('TypeScript consumes frames and selections generated by Go', async () => {
  assert.equal(vectors.format, 1);
  assert.equal(vectors.generatedBy, 'go');
  const sessionId = bytes(vectors.sessionId);
  assertSelectionVectors(sessionId);
  for (const vector of vectors.cases) {
    await assertCaseVector(vector, sessionId);
  }
  assertInvalidVectors();
  for (const vector of vectors.hostile) {
    assertHostileVector(vector);
  }
});

async function makeStream(blocks = 48, frameCount = 1200, sessionSeed = 0) {
  const capsule = vectorCapsule(blocks * BLOCK_SIZE - 13);
  const sessionId = Uint8Array.from(
    { length: 16 },
    (_, index) => sessionSeed + index,
  );
  const encoder = await OpticalEncoder.create(capsule, sessionId);
  const frames = Array.from({ length: frameCount }, (_, sequence) =>
    encoder.frame(0, sequence),
  );
  return { capsule, encoder, frames };
}

async function recover(frames, expected) {
  const decoder = new OpticalDecoder();
  for (const frame of frames) {
    try {
      decoder.add(frame);
    } catch (error) {
      if (
        !(error instanceof OpticalCodecError) ||
        !['crc', 'frame-length'].includes(error.code)
      ) {
        throw error;
      }
    }
    if (decoder.complete) {
      break;
    }
  }
  assert.deepEqual(await decoder.result(), expected);
}

test('loss simulator covers zero loss, reordering, duplicates, truncation, and corruption', async () => {
  const { capsule, frames } = await makeStream();
  await recover(simulateLoss(frames, {}), capsule);
  await recover(
    simulateLoss(frames, {
      reorderWindow: 13,
      duplicateEvery: 9,
      truncateEvery: 17,
      corruptEvery: 23,
    }),
    capsule,
  );
});

test('repair equations recover burst loss and uniform loss through 50 percent', async () => {
  const { capsule, frames } = await makeStream();
  await recover(
    simulateLoss(frames, { burstStart: 0, burstLength: 200 }),
    capsule,
  );
  await recover(simulateLoss(frames, { removeEvery: 10 }), capsule);
  await recover(simulateLoss(frames, { removeEvery: 4 }), capsule);
  await recover(simulateLoss(frames, { removeEvery: 2 }), capsule);
});

test('odd maximum-degree recovery closes a full stripe at the observed phone yield', async () => {
  const capsule = vectorCapsule(MAX_STRIPE_SIZE);
  const sessionId = new Uint8Array(16);
  const encoder = await OpticalEncoder.create(capsule, sessionId);
  const decoder = new OpticalDecoder();
  const sourceFrames = 1024;
  const repairFrames = 256;
  const initialFrames = sourceFrames + repairFrames;
  let nextRepairSequence = initialFrames;
  let emitted = 0;
  let accepted = 0;

  while (!decoder.complete && emitted < 2500) {
    let sequence;
    if (emitted < initialFrames) {
      const repairsBefore = Math.floor(
        (emitted * repairFrames) / initialFrames,
      );
      const repairsThrough = Math.floor(
        ((emitted + 1) * repairFrames) / initialFrames,
      );
      sequence =
        repairsThrough > repairsBefore
          ? sourceFrames + repairsThrough - 1
          : emitted - repairsBefore;
    } else {
      while (
        selectBlocks(sessionId, 0, nextRepairSequence, sourceFrames).length !==
        31
      ) {
        nextRepairSequence++;
      }
      sequence = nextRepairSequence++;
    }
    if ((emitted * 17 + (emitted % 4) * 29) % 100 < 58) {
      decoder.add(encoder.frame(0, sequence));
      accepted++;
    }
    emitted++;
  }

  assert.equal(decoder.complete, true);
  assert.ok(emitted <= 2100, `used ${emitted} displayed symbols`);
  assert.ok(accepted <= Math.ceil(sourceFrames * 1.25));
  assert.deepEqual(await decoder.result(), capsule);
});

test('a receiver joining after the systematic pass reaches full rank', async () => {
  const sourceFrames = 64;
  const capsule = vectorCapsule(BLOCK_SIZE * sourceFrames);
  const sessionId = new Uint8Array(16);
  const encoder = await OpticalEncoder.create(capsule, sessionId);
  const decoder = new OpticalDecoder();
  let sequence = sourceFrames + Math.ceil(sourceFrames * 0.25);

  for (let emitted = 0; emitted < sourceFrames * 4 && !decoder.complete;) {
    if (selectBlocks(sessionId, 0, sequence, sourceFrames).length === 31) {
      decoder.add(encoder.frame(0, sequence));
      emitted++;
    }
    sequence++;
  }

  assert.equal(decoder.complete, true);
  assert.deepEqual(await decoder.result(), capsule);
});

test('mixed sessions and a sender restart cannot merge equation state', async () => {
  const first = await makeStream(12, 200, 1);
  const second = await makeStream(12, 200, 99);
  const decoder = new OpticalDecoder();
  decoder.add(first.frames[0]);
  assert.throws(
    () => decoder.add(second.frames[0]),
    (error) => assertCodecError(error, 'session'),
  );
  for (const frame of first.frames.slice(1)) {
    decoder.add(frame);
    if (decoder.complete) {
      break;
    }
  }
  assert.deepEqual(await decoder.result(), first.capsule);
});

test('an underdetermined stream never exposes a partial capsule', async () => {
  const { frames } = await makeStream(48, 10);
  const decoder = new OpticalDecoder();
  for (const frame of frames) {
    decoder.add(frame);
  }
  assert.equal(decoder.complete, false);
  await assert.rejects(decoder.result(), (error) =>
    assertCodecError(error, 'incomplete'),
  );
});

test('decoder clears retained equations and recovered ciphertext', async () => {
  const { encoder } = await makeStream(2, 2);
  const decoder = new OpticalDecoder();
  decoder.add(encoder.frame(0, 0));
  const equation = decoder.active.get(0).basis.get(0);
  assert.ok(equation.payload.some((byte) => byte !== 0));
  decoder.clear();
  assert.deepEqual(equation.payload, new Uint8Array(BLOCK_SIZE));
  assert.deepEqual(equation.coefficients, new Uint32Array(1));
  assert.equal(decoder.complete, false);

  decoder.add(encoder.frame(0, 0));
  decoder.add(encoder.frame(0, 1));
  const recovered = decoder.recovered.get(0);
  assert.ok(recovered.some((byte) => byte !== 0));
  decoder.clear();
  assert.deepEqual(recovered, new Uint8Array(recovered.byteLength));
});

test('a contradictory equation rejects the session', async () => {
  const { frames } = await makeStream(2, 2);
  const decoder = new OpticalDecoder();
  decoder.add(frames[0]);
  const contradiction = new Uint8Array(frames[0]);
  contradiction[HEADER_SIZE] ^= 1;
  recomputeCrc(contradiction);
  assert.throws(
    () => decoder.add(contradiction),
    (error) => assertCodecError(error, 'contradiction'),
  );
});

test('a digest mismatch rejects a fully reconstructed capsule', async () => {
  const { encoder } = await makeStream(4, 4);
  const decoder = new OpticalDecoder();
  for (let sequence = 0; sequence < encoder.getSourceCount(0); sequence++) {
    const frame = encoder.frame(0, sequence);
    frame[56] ^= 1;
    recomputeCrc(frame);
    decoder.add(frame);
  }
  await assert.rejects(decoder.result(), (error) =>
    assertCodecError(error, 'digest'),
  );
});

