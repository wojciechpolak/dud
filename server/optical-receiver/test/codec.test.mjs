test('decoder budgets bound sessions, distinct frames, equations, and work', async () => {
  assert.equal(MAX_ACTIVE_SESSIONS, 1);
  assert.equal(MAX_DISTINCT_FRAMES, 131_072);
  assert.equal(MAX_RETAINED_EQUATIONS, 41_944);
  assert.equal(MAX_DECODER_WORK_BYTES, 34_359_738_368);

  const encoder = await OpticalEncoder.create(
    vectorCapsule(BLOCK_SIZE * 2),
    new Uint8Array(16),
  );
  const frame0 = encoder.frame(0, 0);
  const frame1 = encoder.frame(0, 1);

  const distinct = new OpticalDecoder({
    maxDistinctFrames: 1,
    maxRetainedEquations: 2,
    maxWorkBytes: Number.MAX_SAFE_INTEGER,
  });
  distinct.add(frame0);
  distinct.add(frame0);
  assert.throws(
    () => distinct.add(frame1),
    (error) => assertCodecError(error, 'distinct-frames'),
  );

  const retained = new OpticalDecoder({
    maxDistinctFrames: 2,
    maxRetainedEquations: 1,
    maxWorkBytes: Number.MAX_SAFE_INTEGER,
  });
  const retainedProgress = retained.add(frame0);
  assert.equal(retainedProgress.retainedEquationCount, 1);
  assert.throws(
    () => retained.add(frame1),
    (error) => assertCodecError(error, 'retained-equations'),
  );

  const work = new OpticalDecoder({
    maxDistinctFrames: 2,
    maxRetainedEquations: 2,
    maxWorkBytes: frame0.byteLength,
  });
  const workProgress = work.add(frame0);
  assert.equal(workProgress.workBytes, frame0.byteLength);
  assert.throws(
    () => work.add(frame1),
    (error) => assertCodecError(error, 'decoder-work'),
  );
});

test('a small capsule has a proportional decoder work limit', async () => {
  const encoder = await OpticalEncoder.create(
    vectorCapsule(BLOCK_SIZE * 2),
    new Uint8Array(16),
  );
  const frame = encoder.frame(0, 0);
  const decoder = new OpticalDecoder();
  assert.throws(
    () => {
      for (let attempt = 0; attempt < 1000; attempt++) {
        decoder.add(frame);
      }
    },
    (error) => {
      assertCodecError(error, 'decoder-work');
      assert.match(error.message, /decoder work limit 1638400 byte operations/);
      return true;
    },
  );
});

test('a low-yield 16 MiB stream completes within bounded decoder work', async () => {
  const capsule = vectorCapsule(16 * 1024 * 1024);
  const sessionId = new Uint8Array(16);
  const encoder = await OpticalEncoder.create(
    capsule,
    sessionId,
    HIGH_DENSITY_BLOCK_SIZE,
  );
  const decoder = new OpticalDecoder();
  let progress;

  for (let stripe = 0; stripe < encoder.stripeCount; stripe++) {
    const sourceCount = encoder.getSourceCount(stripe);
    const repairCount = Math.ceil(sourceCount / 4);
    const cycleLength = sourceCount + repairCount;
    for (let position = 0; position < cycleLength; position++) {
      const repairsBefore = Math.floor((position * repairCount) / cycleLength);
      const repairsThrough = Math.floor(
        ((position + 1) * repairCount) / cycleLength,
      );
      const sequence =
        repairsThrough > repairsBefore
          ? sourceCount + repairsThrough - 1
          : position - repairsBefore;
      if (position % 9 === 0) {
        progress = decoder.add(encoder.frame(stripe, sequence));
      }
    }

    let sequence = sourceCount + repairCount;
    let repairAttempts = 0;
    while (progress.independentRows < sourceCount && repairAttempts < 2000) {
      if (
        selectBlocks(sessionId, stripe, sequence, sourceCount).length ===
        Math.min(31, sourceCount)
      ) {
        progress = decoder.add(encoder.frame(stripe, sequence));
        repairAttempts++;
      }
      sequence++;
    }
    assert.equal(progress.independentRows, sourceCount, `stripe ${stripe}`);
  }

  assert.ok(decoder.complete);
  assert.deepEqual(await decoder.result(), capsule);
  assert.ok(progress.workBytes > 4_294_967_296);
  assert.ok(progress.workBytes < capsule.byteLength * 512);
});

