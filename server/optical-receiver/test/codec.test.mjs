test('high-density frames round-trip across a stripe boundary', async () => {
  const capsule = vectorCapsule(
    HIGH_DENSITY_BLOCK_SIZE * 1024 + HIGH_DENSITY_BLOCK_SIZE + 7,
  );
  const encoder = await OpticalEncoder.create(
    capsule,
    new Uint8Array(16),
    HIGH_DENSITY_BLOCK_SIZE,
  );
  assert.equal(encoder.stripeCount, 2);
  const decoder = new OpticalDecoder();
  for (let stripe = 0; stripe < encoder.stripeCount; stripe++) {
    const count = encoder.getSourceCount(stripe);
    for (let sequence = 0; sequence < count; sequence++) {
      const encoded = encoder.frame(stripe, sequence);
      assert.equal(encoded.byteLength, HIGH_DENSITY_FRAME_SIZE);
      assert.equal(parseFrame(encoded).blockSize, HIGH_DENSITY_BLOCK_SIZE);
      decoder.add(encoded);
    }
  }
  assert.deepEqual(await decoder.result(), capsule);
});

test('format-0 frames are rejected before retaining equations', () => {
  const archived = JSON.parse(
    readFileSync(
      new URL(
        '../../../client/optical-sender/testdata/format0/go-vectors.json',
        import.meta.url,
      ),
      'utf8',
    ),
  );
  for (const item of archived.cases) {
    for (const vector of item.frames) {
      const decoder = new OpticalDecoder();
      assert.throws(
        () => decoder.add(bytes(vector.bytes)),
        (error) =>
          error.code === 'version' &&
          error.message ===
            'version: unsupported optical sender; expected dud/optical/1, received format 0',
      );
      assert.equal(decoder.complete, false);
      const progress = decoder.add(bytes(vectors.cases[0].frames[0].bytes));
      assert.equal(progress.independentFrameCount, 1);
      assert.equal(progress.retainedEquationCount, 1);
      assert.equal(progress.distinctFrameCount, 1);
    }
  }
});
